"""Civ6Ai build priorities: the categories the model can switch on for an AI seat.

Each category becomes three engine AI strategies (light, strong, all-in) in
Data/Civ6Ai_Priorities.sql, generated by scripts/gen_priorities.py. A strategy
is active when the synced game property CIV6AI_PRIO_<player>_<id> equals its
level; the engine asks gameplay Lua (GameEvents.Civ6AiPrio_<id>_<level>) before
each player's turn. When active, the strategy re-weights the engine AI's own
scoring (the same tables Infixo's Real Strategy uses), so the engine still picks
the concrete unit, building and city for the current era.

Weights are percentage adjustments to the engine's base values, the same scale
Real Strategy uses (-100 removes a value, +100 doubles it). Level 2 doubles the
light weights and level 3 multiplies them by four; negatives never go below
-100. District weights are favoured-item values.

The ids are part of the save format (game properties), so never renumber them.
"""
