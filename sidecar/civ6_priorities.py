BY_ID = {c["id"]: c for c in CATEGORIES}
BY_KEY = {c["key"]: c for c in CATEGORIES}


def scaled(value: int, level: int) -> int:
    v = value * LEVEL_MULT[level]
    return max(v, -100)


def strategy_type(cat: dict, level: int) -> str:
    return f"CIV6AI_PRIO_{cat['key'].upper()}_{LEVELS[level].upper()}"


def lua_fn(cat: dict, level: int) -> str:
    return f"Civ6AiPrio_{cat['id']}_{level}"


