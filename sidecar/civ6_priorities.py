# Model integration: legal commands, prompt block, reply parsing.
# ---------------------------------------------------------------------------
COMMAND_KIND = "set_build_priority"
REPLY_KEY = "priorities"


def command_id(cat_id: int, level: int) -> str:
    return f"CMD_PRIO_{cat_id}_{level}"


def current_levels(snapshot: dict) -> dict[int, int]:
    """Active priorities of the seat, from civ6.priorities (written by the mod)."""
    out: dict[int, int] = {}
    block = snapshot.get("civ6") if isinstance(snapshot, dict) else None
    items = block.get("priorities") if isinstance(block, dict) else None
    for item in items or []:
        if not isinstance(item, dict):
            continue
        try:
            cid, lvl = int(item.get("id")), int(item.get("level"))
        except (TypeError, ValueError):
            continue
        if cid in BY_ID and 1 <= lvl <= 3:
            out[cid] = lvl
    return out


def priorities_supported(snapshot: dict) -> bool:
    """Only seats whose mod build reports civ6.priorities get the command."""
    block = snapshot.get("civ6") if isinstance(snapshot, dict) else None
    return isinstance(block, dict) and isinstance(block.get("priorities"), list)


def inject_legal_commands(snapshot: dict) -> int:
    """Add one legal command per category and level (0 switches it off)."""
    if not priorities_supported(snapshot):
        return 0
    from sidecar.civ6_adapter import _enrich_runtime_legal_command

    legal = snapshot.setdefault("legal_commands", [])
    have = {c.get("command_id") for c in legal if isinstance(c, dict)}
    added = 0
    for cat in CATEGORIES:
        for level in (0, 1, 2, 3):
            cid = command_id(cat["id"], level)
            if cid in have:
                continue
            legal.append(_enrich_runtime_legal_command({
                "command_id": cid,
                "kind": COMMAND_KIND,
                "description": f"build priority {cat['key']}:{level}",
                "fixed_arguments": {"priority_id": cat["id"], "priority_level": level},
            }))
            added += 1
    return added


def _fmt(levels: dict[int, int]) -> str:
    if not levels:
        return "none"
    return ", ".join(f"{BY_ID[c]['key']}:{lvl}" for c, lvl in sorted(levels.items()))


def prompt_lines(snapshot: dict) -> list[str]:
    """=== BUILD PRIORITIES === block for the prompt (empty when unsupported)."""
    if not priorities_supported(snapshot):
        return []
    posture = " | ".join(f"{c['key']} ({c['desc']})" for c in CATEGORIES if c["group"] == "posture")
    focus = " | ".join(f"{c['key']} ({c['desc']})" for c in CATEGORIES if c["group"] == "focus")
    return [
        "=== BUILD PRIORITIES ===",
        "Your cities' production is chosen by the game's own AI. Build priorities steer what it builds across "
        "your whole empire (which units, buildings, districts and wonders it favours). They stay on every turn "
        "until you change them.",
        f"Current: {_fmt(current_levels(snapshot))}",
        "Levels: 1 = light, 2 = strong, 3 = all-in (almost nothing else gets built).",
        f"Pick at most ONE posture: {posture}",
        f"Pick at most {MAX_FOCUS} focuses: {focus}",
        f'To change them, add the optional key "{REPLY_KEY}" with your COMPLETE new set, e.g. '
        f'"{REPLY_KEY}": "war:2, production:1, expansion:1". Anything you leave out is switched off. '
        f'"{REPLY_KEY}": "none" switches all off. Omit the key to keep the current set.',
        "Change them when your situation changes (war starts or ends, bankruptcy, a victory plan), not every turn.",
    ]


def parse_reply(value) -> tuple[dict[int, int] | None, list[str]]:
    """Desired complete set from the model's value, plus problems. None = no change."""
    problems: list[str] = []
    if value is None:
        return None, problems
    if isinstance(value, dict):
        items = [f"{k}:{v}" for k, v in value.items()]
    elif isinstance(value, list):
        items = [str(v) for v in value]
    else:
        text = str(value).strip()
        if not text or text.lower() in ("keep", "same", "unchanged", "no change"):
            return None, problems
        if text.lower() in ("none", "clear", "off", "0"):
            return {}, problems
        items = [p for p in text.replace(";", ",").replace("+", ",").split(",")]
    wanted: dict[int, int] = {}
    for raw in items:
        part = raw.strip().strip('"').strip()
        if not part:
            continue
        key, _, lvl_text = part.partition(":")
        key = key.strip().lower().replace(" ", "_").replace("-", "_")
        lvl_text = lvl_text.strip().lower()
        if lvl_text in LEVEL_BY_NAME:
            level = LEVEL_BY_NAME[lvl_text]
        elif lvl_text in ("all-in", "allin"):
            level = 3
        elif lvl_text == "":
            level = 1
        else:
            try:
                level = int(lvl_text)
            except ValueError:
                problems.append(f"bad_level:{part}")
                continue
        cat = BY_KEY.get(key)
        if cat is None:
            problems.append(f"unknown_priority:{key}")
            continue
        if not 0 <= level <= 3:
            problems.append(f"bad_level:{part}")
            continue
        if level > 0:
            wanted[cat["id"]] = level
    postures = [c for c in wanted if BY_ID[c]["group"] == "posture"]
    if len(postures) > 1:
        # Keep the first posture listed (dict keeps insertion order).
        for c in postures[1:]:
            del wanted[c]
        problems.append("too_many_postures")
    focuses = [c for c in wanted if BY_ID[c]["group"] == "focus"]
    if len(focuses) > MAX_FOCUS:
        for c in focuses[MAX_FOCUS:]:
            del wanted[c]
        problems.append("too_many_focus")
    return wanted, problems


def plan_commands(current: dict[int, int], wanted: dict[int, int]) -> list[str]:
    """Legal command ids, switches-off first so a swap never hits the focus cap."""
    offs = [command_id(c, 0) for c in sorted(current) if c not in wanted]
    postures = [command_id(c, l) for c, l in wanted.items() if BY_ID[c]["group"] == "posture" and current.get(c) != l]
    focuses = [command_id(c, l) for c, l in wanted.items() if BY_ID[c]["group"] == "focus" and current.get(c) != l]
    return offs + postures + focuses
